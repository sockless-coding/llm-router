namespace LR.Application.Agents;

/// <summary>
/// The copy-paste installers served at <c>/agent/install.sh</c> and <c>/agent/install.ps1</c>,
/// with the router's URL baked in. Both download the right package for the machine from the
/// router, unpack it, write <c>agent.json</c> (via <c>LR.Agent configure</c>, which keeps an existing
/// install's identity) and register a service that restarts the agent after self-updates.
/// </summary>
public static class AgentInstallScripts
{
    /// <summary>The one-liner shown on the Agents page for Linux.</summary>
    public static string LinuxCommand(string routerUrl, string token) =>
        $"curl -fsSL {routerUrl}/agent/install.sh | sudo sh -s -- {token}";

    /// <summary>The one-liner shown on the Agents page for Windows (elevated PowerShell).</summary>
    public static string WindowsCommand(string routerUrl, string token) =>
        $"& ([scriptblock]::Create((irm '{routerUrl}/agent/install.ps1'))) -Token '{token}'";

    public static string LinuxScript(string routerUrl) => LinuxTemplate.Replace("__ROUTER_URL__", routerUrl).ReplaceLineEndings("\n");

    public static string WindowsScript(string routerUrl) => WindowsTemplate.Replace("__ROUTER_URL__", routerUrl).ReplaceLineEndings("\r\n");

    private const string LinuxTemplate = """
#!/bin/sh
# LLM Router agent installer, generated by the router at __ROUTER_URL__
#   curl -fsSL __ROUTER_URL__/agent/install.sh | sudo sh -s -- <enrollment-token>
# Optional environment: LR_AGENT_INSTALL_DIR (default /opt/lr-agent), LR_AGENT_DATA_DIR (default /var/lib/lr-agent)
set -eu

ROUTER_URL="__ROUTER_URL__"
TOKEN="${1:-${LR_AGENT_TOKEN:-}}"
INSTALL_DIR="${LR_AGENT_INSTALL_DIR:-/opt/lr-agent}"
DATA_DIR="${LR_AGENT_DATA_DIR:-/var/lib/lr-agent}"
SERVICE=lr-agent

if [ -z "$TOKEN" ]; then
  echo "Usage: curl -fsSL $ROUTER_URL/agent/install.sh | sudo sh -s -- <enrollment-token>" >&2
  exit 1
fi
if [ "$(id -u)" -ne 0 ]; then
  echo "Please run as root (pipe into 'sudo sh')." >&2
  exit 1
fi

case "$(uname -m)" in
  x86_64|amd64) RID=linux-x64 ;;
  aarch64|arm64) RID=linux-arm64 ;;
  *) echo "Unsupported architecture: $(uname -m) (supported: x86_64, aarch64)" >&2; exit 1 ;;
esac

fetch() {
  if command -v curl >/dev/null 2>&1; then
    curl -fSL --progress-bar -H "Authorization: Bearer $TOKEN" -o "$2" "$1"
  elif command -v wget >/dev/null 2>&1; then
    wget -q --show-progress --header="Authorization: Bearer $TOKEN" -O "$2" "$1"
  else
    echo "curl or wget is required." >&2
    exit 1
  fi
}

TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT

echo "==> Downloading the LLM Router agent ($RID) from $ROUTER_URL"
fetch "$ROUTER_URL/agent/package/$RID" "$TMP/agent.tar.gz"

HAS_SYSTEMD=0
if command -v systemctl >/dev/null 2>&1 && [ -d /run/systemd/system ]; then HAS_SYSTEMD=1; fi

if [ "$HAS_SYSTEMD" -eq 1 ] && systemctl is-active --quiet "$SERVICE"; then
  echo "==> Stopping the running agent (backends keep running)"
  systemctl stop "$SERVICE"
fi

echo "==> Installing to $INSTALL_DIR (data in $DATA_DIR)"
mkdir -p "$INSTALL_DIR" "$DATA_DIR"
mkdir -p "$TMP/pkg"
tar -xzf "$TMP/agent.tar.gz" -C "$TMP/pkg"
# Rename-over keeps wrapper processes started from the old files running.
( cd "$TMP/pkg" && find . -type d -exec mkdir -p "$INSTALL_DIR/{}" \; )
( cd "$TMP/pkg" && find . -type f ! -name agent.json -exec sh -c 'cp "$1" "$2/$1.new" && mv -f "$2/$1.new" "$2/$1"' _ {} "$INSTALL_DIR" \; )
chmod 755 "$INSTALL_DIR/LR.Agent"
[ -f "$INSTALL_DIR/createdump" ] && chmod 755 "$INSTALL_DIR/createdump"

"$INSTALL_DIR/LR.Agent" configure --config "$INSTALL_DIR/agent.json" --router-url "$ROUTER_URL" --enrollment-token "$TOKEN" --data-dir "$DATA_DIR"

if [ "$HAS_SYSTEMD" -eq 1 ]; then
  cat > "/etc/systemd/system/$SERVICE.service" <<UNIT
[Unit]
Description=LLM Router agent
After=network-online.target
Wants=network-online.target

[Service]
Type=notify
ExecStart=$INSTALL_DIR/LR.Agent --config $INSTALL_DIR/agent.json
WorkingDirectory=$INSTALL_DIR
Restart=always
RestartSec=5
# Backends run in their own wrapper processes; restarting or updating the agent must not kill them.
KillMode=process
Environment=DOTNET_CLI_TELEMETRY_OPTOUT=1

[Install]
WantedBy=multi-user.target
UNIT
  systemctl daemon-reload
  systemctl enable "$SERVICE" >/dev/null 2>&1
  systemctl restart "$SERVICE"
  echo "==> Agent service '$SERVICE' is running. Logs: journalctl -u $SERVICE -f"
else
  echo "==> systemd not found; starting the agent in the background (it won't start at boot)."
  nohup "$INSTALL_DIR/LR.Agent" --config "$INSTALL_DIR/agent.json" >"$DATA_DIR/agent.log" 2>&1 &
  echo "    Log: $DATA_DIR/agent.log"
fi

echo
echo "Done. The agent should appear on the router's Agents page within a few seconds."
echo "Backends started on this machine listen on the ports assigned to their servers (8080 and up);"
echo "make sure the router can reach them (e.g. 'ufw allow from <router-ip> proto tcp to any port 8080:8199')."
""";

    private const string WindowsTemplate = """
# LLM Router agent installer, generated by the router at __ROUTER_URL__
# Run in an elevated PowerShell:
#   & ([scriptblock]::Create((irm '__ROUTER_URL__/agent/install.ps1'))) -Token '<enrollment-token>'
param(
    [Parameter(Mandatory = $true)][string]$Token,
    [string]$InstallDir = (Join-Path $env:ProgramFiles 'LR Agent'),
    [string]$DataDir = (Join-Path $env:ProgramData 'LR Agent'),
    # Inbound TCP ports opened in Windows Firewall for backends (the ports assigned to servers).
    [string]$BackendPorts = '8080-8199'
)
$ErrorActionPreference = 'Stop'
$ProgressPreference = 'SilentlyContinue'
$RouterUrl = '__ROUTER_URL__'
$ServiceName = 'LRAgent'

$principal = New-Object Security.Principal.WindowsPrincipal([Security.Principal.WindowsIdentity]::GetCurrent())
if (-not $principal.IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)) {
    throw 'Please run this from an elevated (Administrator) PowerShell.'
}

$arch = if ($env:PROCESSOR_ARCHITECTURE -eq 'ARM64' -or $env:PROCESSOR_ARCHITEW6432 -eq 'ARM64') { 'arm64' } else { 'x64' }
$rid = "win-$arch"
[Net.ServicePointManager]::SecurityProtocol = [Net.ServicePointManager]::SecurityProtocol -bor [Net.SecurityProtocolType]::Tls12

$tmp = Join-Path ([IO.Path]::GetTempPath()) ("lr-agent-" + [guid]::NewGuid().ToString('N'))
New-Item -ItemType Directory -Path $tmp | Out-Null
try {
    Write-Host "==> Downloading the LLM Router agent ($rid) from $RouterUrl"
    $zip = Join-Path $tmp 'agent.zip'
    Invoke-WebRequest -UseBasicParsing -Headers @{ Authorization = "Bearer $Token" } -Uri "$RouterUrl/agent/package/$rid" -OutFile $zip

    $svc = Get-Service -Name $ServiceName -ErrorAction SilentlyContinue
    if ($svc -and $svc.Status -ne 'Stopped') {
        Write-Host '==> Stopping the running agent (backends keep running)'
        Stop-Service -Name $ServiceName -Force
        $svc.WaitForStatus('Stopped', [TimeSpan]::FromSeconds(30))
    }

    Write-Host "==> Installing to $InstallDir (data in $DataDir)"
    New-Item -ItemType Directory -Force -Path $InstallDir, $DataDir | Out-Null
    $pkg = Join-Path $tmp 'pkg'
    Expand-Archive -Path $zip -DestinationPath $pkg -Force
    Get-ChildItem -Path $pkg -Recurse -File | ForEach-Object {
        $relative = $_.FullName.Substring($pkg.Length).TrimStart('\')
        if ($relative -ieq 'agent.json') { return }
        $target = Join-Path $InstallDir $relative
        New-Item -ItemType Directory -Force -Path (Split-Path $target) | Out-Null
        if (Test-Path $target) {
            try { Remove-Item -Force $target }
            catch { Rename-Item -Path $target -NewName ((Split-Path $target -Leaf) + '.lr-old' + [DateTime]::UtcNow.Ticks) }
        }
        Move-Item -Path $_.FullName -Destination $target
    }

    $exe = Join-Path $InstallDir 'LR.Agent.exe'
    $config = Join-Path $InstallDir 'agent.json'
    & $exe configure --config $config --router-url $RouterUrl --enrollment-token $Token --data-dir $DataDir
    if ($LASTEXITCODE -ne 0) { throw "Configuring the agent failed (exit code $LASTEXITCODE)." }

    if (-not (Get-Service -Name $ServiceName -ErrorAction SilentlyContinue)) {
        New-Service -Name $ServiceName -DisplayName 'LLM Router Agent' -StartupType Automatic `
            -Description 'Runs llama.cpp/stable-diffusion.cpp backends for an LLM Router and keeps them up to date.' `
            -BinaryPathName ('"{0}" --config "{1}"' -f $exe, $config) | Out-Null
    }
    else {
        sc.exe config $ServiceName binPath= ('"{0}" --config "{1}"' -f $exe, $config) start= auto | Out-Null
    }
    # Self-updates exit the process so the service manager starts the new version.
    sc.exe failure $ServiceName reset= 86400 actions= restart/3000/restart/5000/restart/10000 | Out-Null
    sc.exe failureflag $ServiceName 1 | Out-Null

    if (-not (Get-NetFirewallRule -Name 'LRAgentBackends' -ErrorAction SilentlyContinue)) {
        New-NetFirewallRule -Name 'LRAgentBackends' -DisplayName 'LLM Router agent backends' -Direction Inbound `
            -Protocol TCP -LocalPort ($BackendPorts -split ',') -Action Allow | Out-Null
    }

    Start-Service -Name $ServiceName
    Write-Host "==> Agent service '$ServiceName' is running."
    Write-Host ''
    Write-Host "Done. The agent should appear on the router's Agents page within a few seconds."
}
finally {
    Remove-Item -Recurse -Force $tmp -ErrorAction SilentlyContinue
}
""";
}
